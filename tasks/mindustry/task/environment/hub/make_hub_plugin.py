"""Pack the hidden game (tests/hidden/: the game host, the world profile and the bridge source) for the hub and the oracle.

    python3 task/environment/hub/make_hub_plugin.py

writes two generated, git-ignored files:
- task/build/mmf_hub_plugin.py, a board plugin. On import, on the hub, it unpacks the game into /opt/mindustry-many-fronts.
  List it first in --ek board_plugins, before game_plugin.py.
- task/solution/hub_bundle.tar.gz, the same files, for the plain Harbor oracle (solution/solve.sh). /solution reaches the
  container only through Harbor's oracle agent, never an agent's sandbox.
The agents' image (environment/Dockerfile) holds only the public server JAR and docs, so the game is in no agent sandbox.
"""
import base64
import io
import os
import tarfile

HERE = os.path.dirname(os.path.abspath(__file__))          # task/environment/hub
TASK = os.path.dirname(os.path.dirname(HERE))              # task/
DEST = "opt/mindustry-many-fronts"

PLUGIN = '''"""Generated by make_hub_plugin.py. Do not edit or commit. Unpacks the hidden game on the hub; list it before game_plugin.py."""
import base64
import io
import tarfile

BUNDLE = "{bundle}"

with tarfile.open(fileobj=io.BytesIO(base64.b64decode(BUNDLE)), mode="r:gz") as tf:
    tf.extractall("/", filter="data")


def register(board, api, mcp):
    return None
'''


def bundle() -> bytes:
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tf:
        def add(path, arc):
            info = tf.gettarinfo(path, arcname=arc)
            info.mode, info.uid, info.gid, info.uname, info.gname, info.mtime = 0o755 if info.isdir() else 0o644, 0, 0, "root", "root", 0
            with open(path, "rb") as f:
                tf.addfile(info, f)
        root = os.path.join(TASK, "tests", "hidden")
        for d, dirs, files in os.walk(root):
            dirs[:] = sorted(x for x in dirs if x != "__pycache__")
            for name in sorted(files):
                if not name.endswith(".pyc"):
                    p = os.path.join(d, name)
                    add(p, os.path.join(DEST, os.path.relpath(p, root)))
    return buf.getvalue()


def main():
    data = bundle()
    os.makedirs(os.path.join(TASK, "build"), exist_ok=True)
    with open(os.path.join(TASK, "build", "mmf_hub_plugin.py"), "w") as f:
        f.write(PLUGIN.replace("{bundle}", base64.b64encode(data).decode()))
    with open(os.path.join(TASK, "solution", "hub_bundle.tar.gz"), "wb") as f:
        f.write(data)
    print(f"hub bundle: {len(data) / 1024:.0f} KB -> build/mmf_hub_plugin.py, solution/hub_bundle.tar.gz")


if __name__ == "__main__":
    main()
