"""Package the hidden live day for the hub. The simulator engine (environment/engine), the live day's schedule, weather,
events and the server never enter an agent sandbox. The hub gets its own copy of the engine, so nothing a team writes into /app changes the live day.

    python3 environment/hub/hub_bundle.py OUT_DIR

writes atc_hub_plugin.py into OUT_DIR (make_team_task.py uses task/build/): a board plugin the board loads first. On
import it unpacks /opt/dxb-atc on the hub.
"""
import base64
import io
import os
import sys
import tarfile

HUB = os.path.dirname(os.path.abspath(__file__))
TASK = os.path.dirname(os.path.dirname(HUB))
DEST = "opt/dxb-atc"

PLUGIN = '''"""Generated by hub_bundle.py. Do not edit or commit. Unpacks the hidden game on the hub; list it before atc_plugin.py."""
import base64
import io
import tarfile

BUNDLE = "{bundle}"

with tarfile.open(fileobj=io.BytesIO(base64.b64decode(BUNDLE)), mode="r:gz") as tf:
    tf.extractall("/", filter="data")


def register(board, api, mcp):
    return None
'''


def bundle() -> bytes:
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tf:
        def add(path, arc):
            info = tf.gettarinfo(path, arcname=arc)
            info.mode, info.uid, info.gid, info.uname, info.gname, info.mtime = 0o755 if info.isdir() else 0o644, 0, 0, "root", "root", 0
            with open(path, "rb") as f:
                tf.addfile(info, f)
        for root, prefix in ((os.path.join(HUB, "server"), DEST),
                             (os.path.join(TASK, "environment", "engine", "atcsim"), DEST + "/atcsim")):
            for d, dirs, files in os.walk(root):
                dirs[:] = sorted(x for x in dirs if x != "__pycache__")
                for name in sorted(files):
                    if not name.endswith(".pyc"):
                        p = os.path.join(d, name)
                        add(p, os.path.join(prefix, os.path.relpath(p, root)))
    return buf.getvalue()


def main(run_task):
    data = bundle()
    with open(os.path.join(run_task, "atc_hub_plugin.py"), "w") as f:
        f.write(PLUGIN.replace("{bundle}", base64.b64encode(data).decode()))
    print(f"hub bundle: {len(data) / 1024:.0f} KB")


if __name__ == "__main__":
    main(sys.argv[1])
