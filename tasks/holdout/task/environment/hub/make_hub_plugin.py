"""Pack the hidden game (tests/hidden/) for the hub and for the oracle. The game never enters the image's build context
(environment/), so it is in no agent sandbox.

    python3 task/environment/hub/make_hub_plugin.py

writes, inside task/ (both are git-ignored, because they carry the game):
- build/holdout_hub_plugin.py, a board plugin the board loads first. On import it unpacks the game to /opt/holdout
  (root-only).
- solution/hub_bundle.tar.gz, the same files, for solution/solve.sh (plain Harbor has no hub).
"""
import base64
import io
import os
import tarfile

HERE = os.path.dirname(os.path.abspath(__file__))
TASK = os.path.dirname(os.path.dirname(HERE))
HIDDEN = os.path.join(TASK, "tests", "hidden")
DEST = "opt/holdout"

PLUGIN = '''"""Generated by make_hub_plugin.py. Do not edit or commit. Unpacks the hidden game on the hub; list it before game_plugin.py."""
import base64
import io
import os
import tarfile

BUNDLE = "{bundle}"

with tarfile.open(fileobj=io.BytesIO(base64.b64decode(BUNDLE)), mode="r:gz") as tf:
    tf.extractall("/", filter="data")
os.chmod("/opt/holdout", 0o700)


def register(board, api, mcp):
    return None
'''


def bundle() -> bytes:
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tf:
        def add(path, arc):
            info = tf.gettarinfo(path, arcname=arc)
            info.mode, info.uid, info.gid, info.uname, info.gname, info.mtime = 0o755 if info.isdir() else 0o644, 0, 0, "root", "root", 0
            with open(path, "rb") as f:
                tf.addfile(info, f)
        for d, dirs, files in os.walk(HIDDEN):
            dirs[:] = sorted(x for x in dirs if x != "__pycache__")
            for name in sorted(files):
                if not name.endswith(".pyc"):
                    p = os.path.join(d, name)
                    add(p, os.path.join(DEST, os.path.relpath(p, HIDDEN)))
    return buf.getvalue()


def main():
    data = bundle()
    os.makedirs(os.path.join(TASK, "build"), exist_ok=True)
    with open(os.path.join(TASK, "build", "holdout_hub_plugin.py"), "w") as f:
        f.write(PLUGIN.replace("{bundle}", base64.b64encode(data).decode()))
    with open(os.path.join(TASK, "solution", "hub_bundle.tar.gz"), "wb") as f:
        f.write(data)
    print(f"hub bundle: {len(data) / 1024:.0f} KB -> task/build/holdout_hub_plugin.py, task/solution/hub_bundle.tar.gz")


if __name__ == "__main__":
    main()
