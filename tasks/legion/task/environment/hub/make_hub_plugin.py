"""Write the hub's board plugin that carries Petra and the trusted match harness, for team runs.

    python3 task/environment/hub/make_hub_plugin.py [--out task/build/legion_hub_plugin.py] [--pool 30] [--slots 3]

Petra is removed from the image (environment/Dockerfile), and the hub and every agent sandbox are built from it, so
Petra reaches the hub in this plugin. On import, on the hub, it unpacks /opt/legion-hub: petra.zip (Petra's original
files), the trusted harness (tests/harness plus the dev gauntlet) and practice_run.py, and it sets the practice pool
and slots for practice_plugin.py. List it first in --ek board_plugins. Agents run in their own sandboxes and cannot
read the hub's files. The verifier does not need it: it takes Petra and the harness from tests/.

Petra is tests/hidden/petra.zip: the 32 files under simulation/ai/petra/ of the pinned 0ad-data package (0.28.0-1~bpo13+1),
byte for byte; its sha256 is checked against tests/hidden/petra.zip.sha256 before anything is packed. The plugin is
generated (it embeds Petra) and git-ignored.
"""
import argparse
import base64
import hashlib
import io
import os
import tarfile

HERE = os.path.dirname(os.path.abspath(__file__))          # task/environment/hub
TASK = os.path.dirname(os.path.dirname(HERE))              # task/
PETRA = os.path.join(TASK, "tests", "hidden", "petra.zip")
SOURCES = {  # source folder -> where it goes on the hub
    os.path.join(TASK, "tests", "harness"): "opt/legion-hub/harness",
}
FILES = {  # single files -> where they go on the hub
    PETRA: "opt/legion-hub/petra.zip",
    os.path.join(HERE, "practice_run.py"): "opt/legion-hub/practice_run.py",
    # practice_play(dev_first=N) plays the dev gauntlet the team has in /app/harness/, from the hub's own copy
    os.path.join(TASK, "environment", "app", "harness", "dev_gauntlet.json"): "opt/legion-hub/harness/dev_gauntlet.json",
}

PLUGIN = '''"""Generated by make_hub_plugin.py. Do not edit or commit.

Unpacks Petra and the trusted match harness (/opt/legion-hub) on the hub when the board loads this plugin, and
sets the practice pool. List it before practice_plugin.py.
"""
import base64
import io
import os
import tarfile

BUNDLE = "{bundle}"
os.environ["LEGION_PRACTICE_POOL"] = "{pool}"
os.environ["LEGION_PRACTICE_SLOTS"] = "{slots}"


def unpack(root="/"):
    with tarfile.open(fileobj=io.BytesIO(base64.b64decode(BUNDLE)), mode="r:gz") as tf:
        try:
            tf.extractall(root, filter="data")
        except TypeError:   # Python before 3.11.4 has no extraction filters
            tf.extractall(root)


try:
    unpack()
except PermissionError:   # the board does not run as root: unpack under its home, and point the office there
    home = os.path.join(os.path.expanduser("~"), "legion-hub")
    unpack(home)
    os.environ["LEGION_HUB_DIR"] = f"{home}/opt/legion-hub"
    os.environ["LEGION_PRACTICE_STATE"] = f"{home}/state"


def register(board, api, mcp):
    return None
'''


def _skip(name):
    return "__pycache__" in name or name.endswith(".pyc")


def check_petra():
    want = open(PETRA + ".sha256").read().split()[0]
    got = hashlib.sha256(open(PETRA, "rb").read()).hexdigest()
    if got != want:
        raise SystemExit(f"tests/hidden/petra.zip has sha256 {got}, expected {want}")


def bundle() -> bytes:
    check_petra()
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tf:
        def add(path, arcname):
            info = tf.gettarinfo(path, arcname=arcname)
            info.mode = 0o755 if info.isdir() else 0o644    # the game runs as the unprivileged user "legion"
            info.uid = info.gid = 0
            info.uname = info.gname = "root"
            info.mtime = 0
            with open(path, "rb") as fh:
                tf.addfile(info, fh)

        for src, dst in SOURCES.items():
            for root, dirs, files in os.walk(src):
                dirs[:] = sorted(d for d in dirs if not _skip(d))
                for f in sorted(files):
                    if not _skip(f):
                        path = os.path.join(root, f)
                        add(path, os.path.join(dst, os.path.relpath(path, src)))
        for src, dst in FILES.items():
            add(src, dst)
    return buf.getvalue()


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--out", default=os.path.join(TASK, "build", "legion_hub_plugin.py"))
    p.add_argument("--pool", type=int, default=30, help="practice matches against Petra for the whole team")
    p.add_argument("--slots", type=int, default=3, help="practice games the hub plays at once")
    a = p.parse_args()
    if a.pool < 0 or a.slots < 1:
        raise SystemExit("--pool must be 0 or more and --slots at least 1")
    data = bundle()
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, "w") as f:
        f.write(PLUGIN.replace("{bundle}", base64.b64encode(data).decode())
                .replace("{pool}", str(a.pool)).replace("{slots}", str(a.slots)))
    print(f"wrote {os.path.relpath(a.out)}: {len(data) / 1024:.0f} KB; practice pool {a.pool} matches, {a.slots} at once")


if __name__ == "__main__":
    main()
