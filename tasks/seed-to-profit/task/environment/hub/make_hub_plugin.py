"""Write build/seedprofit_hub_plugin.py, the board plugin that carries the hidden market simulator to the hub.

    python3 environment/hub/make_hub_plugin.py        # from task/

The agents' image has no market simulator. The hub is built from the same image, so the simulator reaches it as a
board plugin instead: this script packs tests/hidden/marketsim into build/seedprofit_hub_plugin.py. List that plugin
first in --ek board_plugins, before market_plugin.py. When the board loads it, it unpacks /opt/marketsim on the hub
(root only) and writes the live company's settings: a launch phase of an hour, then 37 simulated months over the
next 2 h 55 min, in a market drawn fresh for every run. The verifier's tests/ reaches the hub only when the agents are
done, and tests/test.sh unpacks the simulator from tests/hidden when the plugin did not run (plain Harbor).

The plugin embeds the hidden simulator, so build/ is git-ignored: don't publish it.
"""
import base64
import gzip
import io
import json
import os
import tarfile

TASK = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SOURCE = os.path.join(TASK, "tests", "hidden", "marketsim", "marketsim")
OUT = os.path.join(TASK, "build", "seedprofit_hub_plugin.py")

# The live company of the published runs (4 hours): the launch phase is the first quarter of the run, then 37 months
# end 5 minutes before time is up; the announced market change comes on day 540. docs/REFERENCE.md states the same.
# SEEDPROFIT_RUN_SEC scales this clock to a shorter run (with --ak timeout_sec set to match), for quick checks of the
# pipeline only: the manual still says 4 hours.
RUN_SEC = float(os.environ.get("SEEDPROFIT_RUN_SEC") or 14400)
LAUNCH_SEC = RUN_SEC * 0.25
MONTHS = 37
LIVE = {"launch_sec": LAUNCH_SEC, "month_sec": round((RUN_SEC - LAUNCH_SEC - 300) / MONTHS, 2), "months": MONTHS,
        "change_day": 540, "shape": "mnl"}

PLUGIN = '''"""Generated by environment/hub/make_hub_plugin.py. Do not edit or publish.

Unpacks the hidden market simulator (/opt/marketsim) on the hub when the board loads this plugin, and writes the live
company's settings. List it before market_plugin.py.
"""
import base64
import io
import json
import os
import tarfile

BUNDLE = "{bundle}"
LIVE_SETTINGS = {live}   # the world_seed is drawn when the hub starts: a fresh market every run


def unpack(root="/"):
    with tarfile.open(fileobj=io.BytesIO(base64.b64decode(BUNDLE)), mode="r:gz") as tf:
        try:
            tf.extractall(root, filter="data")
        except TypeError:   # Python before 3.11.4 has no extraction filters
            tf.extractall(root)


# This file holds the simulator: close it, and the folder of board plugins, to everyone but the board's user.
try:
    os.chmod(__file__, 0o600)
    os.chmod(os.path.dirname(os.path.abspath(__file__)), 0o700)
except OSError:
    pass
_state = os.environ.get("SEEDPROFIT_OFFICE_STATE", "/var/lib/seedprofit-hub")
try:
    os.makedirs(os.path.join(_state, "live"), exist_ok=True)
    os.chmod(_state, 0o700)
    os.chmod(os.path.join(_state, "live"), 0o700)
    _p = os.path.join(_state, "live", "live.json")
    if not os.path.exists(_p):   # a hub restored from a checkpoint keeps its company
        with open(_p, "w") as f:
            json.dump(dict(LIVE_SETTINGS, world_seed=os.urandom(16).hex()), f)
except OSError:
    pass
try:
    unpack()
    os.chmod("/opt/marketsim", 0o700)
except PermissionError:   # the board does not run as root: unpack under its home, and point the office there
    home = os.path.join(os.path.expanduser("~"), "seedprofit-hub")
    unpack(home)
    os.environ["SEEDPROFIT_OFFICE_PYTHONPATH"] = f"{{home}}/opt/marketsim"


def register(board, api, mcp):
    return None
'''


def _skip(name):
    return "__pycache__" in name or name.endswith(".pyc")


def bundle() -> bytes:
    buf = io.BytesIO()
    with gzip.GzipFile(fileobj=buf, mode="wb", mtime=0) as gz, tarfile.open(fileobj=gz, mode="w") as tf:
        for root, dirs, files in os.walk(SOURCE):
            dirs[:] = sorted(d for d in dirs if not _skip(d))
            for f in sorted(files):
                if _skip(f):
                    continue
                path = os.path.join(root, f)
                info = tf.gettarinfo(path, arcname=os.path.join("opt/marketsim/marketsim", os.path.relpath(path, SOURCE)))
                info.mode, info.uid, info.gid, info.uname, info.gname, info.mtime = 0o644, 0, 0, "root", "root", 0
                with open(path, "rb") as fh:
                    tf.addfile(info, fh)
    return buf.getvalue()


def main():
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    text = PLUGIN.format(bundle=base64.b64encode(bundle()).decode(), live=repr(LIVE))
    with open(OUT, "w") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(OUT, TASK)} ({len(text) // 1024} KB)")


if __name__ == "__main__":
    main()
