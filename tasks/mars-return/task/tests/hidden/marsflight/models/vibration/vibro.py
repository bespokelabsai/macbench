"""Launch vibration, acoustics, pyroshock and pogo.

Three environments that size and break hardware but that a quasi-static load check misses:

- Liftoff acoustics. The rocket exhaust radiates sound power W = 0.005 n F Ue (NASA SP-8072, Acoustic Loads
  Generated by the Propulsion System, 1971, eq. 1, page 28), sound power level Lw = 10 log10(W) + 120 dB
  (eq. 2). The level inside the payload fairing falls with the square of the distance from the nozzles and by
  a constant that holds the fairing's noise reduction, the ground reflection and the deflector:
  L = Lw - 20 log10(r) - K. K is fitted once to the Falcon 9 user's guide (131.4 dB, see FALCON9_*), and
  checked against the Atlas V 400 and 500 series (results/issue-75). The random vibration of hardware is
  driven by this sound field (Atlas V Launch Services User's Guide, March 2010, section 3.2.3, page 3-24),
  so it scales decibel for decibel with the acoustic level (Barrett, NASA TN D-1836, 1963) and the acoustic
  qualification level covers it.
- Pyrotechnic shock at every separation plane: the clamp band level of the Falcon 9 user's guide, felt by the
  elements on both sides of the plane. Shock from planes further away is left out: it dies over the distance
  and the joints (Falcon 9 user's guide, section 4.3.4, page 26).
- Pogo: the coupling of the stack's first longitudinal mode with the propellant feed lines of a pump-fed stage
  (Lewis, NASA TN D-5394, 1969, the simplified model of its equations 4, 5 and 35), judged with NASA SP-8055
  (Prevention of Coupled Structure-Propulsion Instability (Pogo), 1970): structural damping of 1 percent
  (page 22) and the damping gain margin of 6 dB (pages 14, 26 and 27).

Every element above the first stage has a qualification level for acoustics and shock (design fields
qual_acoustic_dB and qual_shock_g). An element flown beyond its level can break: the margin it really has
above its qualification level is part of the hidden as-built truth (program.vibro_truth).

Added, each behind a switch MARSFLIGHT_<NAME>=0/1 (switch() below; SWITCHES gives the defaults):

- VIBRO_AERO: the aerodynamic noise of ascent (transonic and max-q), NASA-HDBK-7005 (2001) section 4.5.1.1,
  eq. 4.14, through the same fairing noise reduction as the liftoff noise.
- VIBRO_SHOCK_JOINTS: separation shock beyond the two elements beside the plane, 40% less per joint up to three
  joints (NASA-HDBK-7005 section 5.3.2, after Barrett's Viking lander criteria; NASA-STD-7003A uses the same).
- VIBRO_MARS_NOISE: the liftoff noise of a Mars ascent, in Mars air (lower acoustic impedance rho c).
- VIBRO_POGO_TN5714: Lewis's force-feedback gain refitted to the Saturn V analysis of von Pragenau (NASA TN D-5714,
  1970): AS-502's S-IC about 5 dB unstable at 5 Hz at 120 s of flight.
- VIBRO_LOCAL_POGO: a local pogo mode of a center engine on a crossbeam (AS-503 to AS-508, the S-II's 16 to 18 Hz
  "mini-pogo"), with a one-degree-of-freedom crossbeam model.
"""
from __future__ import annotations

import math
import os

import numpy as np

from ... import data as D

# ---------------------------------------------------------------------------- switches
SWITCHES = {"VIBRO_AERO": True, "VIBRO_SHOCK_JOINTS": True, "VIBRO_MARS_NOISE": True,
            "VIBRO_POGO_TN5714": True, "VIBRO_LOCAL_POGO": True}


def switch(name):
    """Whether one of these models is on: MARSFLIGHT_<name>=0 or 1, else its default in SWITCHES."""
    v = os.environ.get("MARSFLIGHT_" + name)
    if v is None or v == "":
        return SWITCHES[name]
    return v.strip().lower() not in ("0", "false", "off", "no")

# ---------------------------------------------------------------------------- acoustics
SP8072_POWER_FACTOR = 0.005            # W = 0.005 n F Ue (SP-8072 eq. 1, page 28: 1 percent efficiency)
# Falcon 9 user's guide, revision 2 (October 2015), table 4-4, page 25: maximum predicted acoustic environment
# inside the fairing (P95/50, 60% fill factor), full octave bands. OASPL 131.4 dB.
FALCON9_OCTAVE_DB = {31.5: 122.4, 63: 124.7, 125: 126.1, 250: 125.2, 500: 120.1, 1000: 114.4, 2000: 110.8,
                     4000: 107.8, 8000: 104.8}
FALCON9_OASPL_DB = 131.4
# K, in dB, fitted so that the validation Falcon 9 (our validation notes, not included) gives 131.4 dB:
# results/issue-75/acoustics_check.py prints the fit.
FAIRING_K_DB = 32.35
# Qualification margins of the Falcon 9 user's guide, table 4-2, page 25: acoustic qualification at the limit
# level + 6 dB, shock qualification at the limit level + 3 dB.
ACOUSTIC_QUAL_MARGIN_DB = 6.0
SHOCK_QUAL_MARGIN_DB = 3.0
# Protoqualification, the margin of hardware that flies after its test (same table): acoustics at the limit + 3 dB.
ACOUSTIC_PROTOQUAL_MARGIN_DB = 3.0

# ---------------------------------------------------------------------------- ascent aerodynamic noise
# NASA-HDBK-7005 (March 2001) section 4.5.1.1, eq. 4.14: the overall fluctuating pressure level under a turbulent
# boundary layer, L = 20 log10(Cq q / sqrt(1 + 0.14 M^2) / 20 uPa). Cq = 0.02 is the handbook's recommendation
# for attached flow over a space vehicle; 0.03 to 0.1 for separated flow in subsonic and transonic flight. Above
# about Mach 0.85 shocks interact with the boundary layer (section 3.8, page 22) and near the forward end this
# often gives levels above those of max-q. The low end, 0.03, is taken for 0.85 <= M <= 1.2: with 0.1 the
# validation Falcon 9 would hear 138 dB in its fairing at Mach 1, above the user's guide envelope of 131.4 dB that
# covers the transonic phase (results/issue-121/aero_check.py).
TBL_CQ_ATTACHED = 0.02
TBL_CQ_SEPARATED = 0.03
TRANSONIC_MACH = (0.85, 1.2)
# The fairing's noise reduction, outside to inside. SP-8072 eq. 5 gives the level on the vehicle's skin as
# Lw,b - 10 log r^2 - 11 + DI; K above holds those 11 dB of spherical spreading, so what is left of K
# (21.35 dB) is the noise reduction with the directivity, which is taken as the noise reduction for the
# aerodynamic field too (HDBK-7005 section 4.6: one noise reduction, with efficiency factors that it leaves to
# measurements). A capsule outside a fairing gets the same number, as at liftoff.
FAIRING_NR_DB = FAIRING_K_DB - 11.0

# ---------------------------------------------------------------------------- Mars liftoff noise
# The same sound power makes a lower pressure in thin air: for a power W through an area, p^2 = rho c W / A, so the
# level shifts by 10 log10(rho c / rho0 c0) against sea level air (rho0 c0 = 1.225 x 340.3 = 416.9 Pa s/m). Mars air
# at the surface is about 0.02 kg/m^3 with sound at 240 m/s (Maurice et al., In situ recording of Mars soundscape,
# Nature 605, 653, 2022), so about 20 dB lower. The site's own density and sound speed come from the simulator's
# Mars atmosphere (checks.py).
EARTH_RHO_C = 1.225 * 340.3

# ---------------------------------------------------------------------------- shock
# Falcon 9 user's guide table 4-5, page 26: clamp band separation shock at the separation plane, SRS 30 g at
# 100 Hz rising to 1000 g from 1 to 10 kHz. The peak is the level that matters for qualification.
SEPARATION_SHOCK_G = 1000.0
SEPARATION_SRS = {100: 30.0, 1000: 1000.0, 10000: 1000.0}
# NASA-HDBK-7005 section 5.3.2 (page 112), after Barrett's Viking lander criteria (its ref. 5.63): the peak of a
# shock response spectrum falls 40% per joint in the path, for up to three joints. Each element boundary in the
# stack is one joint. Distance along the structure attenuates the shock further (its figures 5.7 to 5.9); that is
# left out, so the levels beyond the plane are upper bounds.
JOINT_ATTENUATION = 0.40
MAX_JOINTS = 3

# ---------------------------------------------------------------------------- qualification fields
# The baseline is a Falcon 9 payload: the user's guide limit levels plus its qualification margins. Unless the design
# sets a level, a payload element is built to its own predicted liftoff level plus the protoqualification margin,
# and never below the baseline (vehicle._check_stack). That default costs no mass: the simulator's mass models are
# fitted to flown hardware, which was built for the environment it flew in. A level above or below the default
# costs or saves mass (hardening_mass).
DEFAULT_QUAL_ACOUSTIC_DB = FALCON9_OASPL_DB + ACOUSTIC_QUAL_MARGIN_DB                     # 137.4 dB
DEFAULT_QUAL_SHOCK_G = SEPARATION_SHOCK_G * 10 ** (SHOCK_QUAL_MARGIN_DB / 20)              # 1413 g
QUAL_ACOUSTIC_RANGE = (125.0, 160.0)
QUAL_SHOCK_RANGE = (300.0, 20000.0)
# Hardware is sized for vibration through its structure: brackets, panels and fittings take loads that grow
# with the acoustic pressure amplitude (10^(dB/20)) and with the shock acceleration. The structure is about a
# fifth of a spacecraft's dry mass (ESA AIM, Facts and Figures, 2016: 63 kg of 317 kg; the HabEx study,
# arXiv:1809.09674: about 25%), so that fraction of the element's mass outside its tanks, engines, heat shield and
# ballast scales with the qualification load against the default level.
STRUCTURE_FRACTION = 0.20

# ---------------------------------------------------------------------------- pogo
STRUCTURAL_DAMPING = 0.01              # SP-8055 page 22: no more than 1 percent of critical
POGO_GAIN_MARGIN_DB = 6.0              # SP-8055 pages 14 and 26: damping gain margin for design
# Lewis's force-feedback amplitude and phase at resonance (n, theta), from his example's oxygen system late in
# the burn (TN D-5394 table II, 95 and 100 percent of burn time: n = 0.96 and 1.12, theta = -81 and -72 deg).
LEWIS_N = 1.0
LEWIS_THETA = math.radians(-75.0)
# Sharpness of the feed-system resonance: tan(psi) = Q (1 - w^2 / wp^2), with Q = |Z'|^2 / (R' w L), from the
# same example at 95 percent of burn (R' = 0.048, X' = 0.034 lb s/in^5, a 30 in line of 36 in^2, w = 126 /s).
FEED_Q = 6.4
# Suction lines are sized for the flow speed of the Saturn V S-IC LOX lines: 17 inch lines (enginehistory.org,
# U.S. Manned Rocket Propulsion Evolution, part 8.10) carrying each F-1's 1,789 kg/s of LOX: 10.7 m/s.
LINE_SPEED = 10.7
# Cavitation compliance at the pump inlet, per unit of volume flow through the pump (m^3/Pa per m^3/s). Fitted
# so that the validation Saturn V's S-IC LOX system (final_saturn_v_Bp.json, rigid ducts, no accumulator)
# resonates at 5.5 Hz, the F-1 oscillation that coupled on AS-502 (Larsen, NASA Experience with Pogo in
# Human Spaceflight Vehicles, RTO-MP-AVT-152, 2008, page 5-9). results/issue-75/
# pogo_check.py prints the fit.
CAVITATION_COMPLIANCE_PER_FLOW = 2.74e-9
GAS_GAMMA = 1.4                        # accumulator gas compressed adiabatically at pogo frequencies
# Refit of the gain n: von Pragenau, Stability of Constant-Gain Systems with Vector Feedback, NASA TN D-5714
# (1970), page 20, the Apollo-Saturn V pogo analysis: at 120 s of flight AS-502's S-IC is "approximately 5 dB
# unstable" at 5 Hz, and AS-504 with helium accumulators is 6 dB stable. With n = 1 the validation Saturn V's S-IC
# is 6.5 dB unstable at 120 s; n scales the damping needed, so n = 10^(-1.5/20) = 0.84 gives the 5 dB
# (results/issue-121/pogo_check.py). The unstable window moves from 85-129 s to 95-129 s of the burn, against
# 105-140 s flown (Larsen 2008).
LEWIS_N_TN5714 = 0.83

# ---------------------------------------------------------------------------- local pogo
# AS-503 to AS-508: the S-II's center J-2 sat on a crossbeam and oscillated with the LOX tank bottom at 16 to 18 Hz
# (Larsen, RTO-MP-AVT-152, 2008, pages 5-10 to 5-13): AS-503 18 Hz about 50 s before cutoff; AS-504 17 Hz from 500
# to 540 s, +-12 g against a 15 g structural limit; AS-508 diverged at 16 Hz to about 34 g, 330 s into flight, and
# the center engine shut down. A helium-bleed accumulator on the center engine's LOX line (AS-509 on) ended it.
# A center engine is taken to sit on a crossbeam when the cluster is odd with five or more engines.
LOCAL_POGO_MIN_ENGINES = 5
# The local model is one degree of freedom: the center engine and the liquid that moves with the aft dome, on the
# crossbeam's spring. The crossbeam is sized by the engine's thrust across the stage: a beam of fixed depth to span
# ratio and working stress deflects by a fixed fraction of the span under its design load, so k = C F / D.
# C and the share of the aft tank's liquid that moves with the dome are fitted to the flights: 16 Hz at 43% of the
# S-II burn (AS-508) and 17.5 Hz at 90% (AS-503 and AS-504) for the validation Saturn V (pogo_check.py).
CROSSBEAM_STIFFNESS = 130.3            # k D / F, dimensionless: thrust deflects the beam by D / 130
DOME_LIQUID_SHARE = 0.00135            # of the aft tank's liquid left
# The local mode couples through the center engine's LOX line, as on the S-II. When the LOX tank is aft, that line is
# a short duct from the aft dome's sump to the pump inlet. Its length is fitted (with the F-1 cavitation compliance
# per flow above) so that the S-II center engine's LOX line resonates above its local mode, as the flights show:
# raising the LOX tank pressure on AS-504 was meant to raise the line frequency further from the structure (Larsen
# page 5-11). 2.0 m puts it at 19.5 Hz. When the LOX tank is on top, the line is the long one of the stack check.
LOCAL_DUCT_M = 2.0
# Which tank is aft: the oxidizer of hydrogen and methane stages (S-II, S-IVB, Centaur, Super Heavy), the fuel of
# kerosene stages (S-IC, Falcon 9, Atlas). The simulator's tank layout puts the oxidizer on top for mass and
# buckling; only this check uses the aft tank.
LOX_AFT_FUELS = ("LH2", "LCH4")


def payload_flags(kinds):
    """Which elements, given their kinds bottom first, are payload with vibration qualification levels: every
    element a fairing covers, and every element that is not a stage, except fairings and the bottom element.
    Launch vehicle stages outside a fairing are left to the structural checks of sim.check_structure."""
    out, covered = [], False
    for i, k in enumerate(kinds):
        out.append(i > 0 and k != "fairing" and (covered or k != "stage"))
        covered = covered or k == "fairing"
    return out


def _propellant_rho(prop):
    return D.PROPELLANTS[prop]["rho"] if prop in D.PROPELLANTS else 1000.0


def qual_fields(e, s, f, errors, where):
    """Read an element's qualification levels and add the mass of hardening it to them."""
    e.qual_acoustic_dB = f(s, "qual_acoustic_dB", *QUAL_ACOUSTIC_RANGE, errors, where, default=DEFAULT_QUAL_ACOUSTIC_DB)
    e.qual_acoustic_set = "qual_acoustic_dB" in s
    e.qual_shock_g = f(s, "qual_shock_g", *QUAL_SHOCK_RANGE, errors, where, default=DEFAULT_QUAL_SHOCK_G)
    acc = s.get("pogo_accumulator_L", 0.0) if e.is_stage else 0.0
    if isinstance(acc, (int, float)):
        acc = {"ox": acc}
    e.pogo_accumulator_L = {}
    if isinstance(acc, dict):
        for role in ("fuel", "ox"):
            if role in acc:
                e.pogo_accumulator_L[role] = f(acc, role, 0.0, 5000.0, errors, f"{where} pogo_accumulator_L")
    else:
        errors.append(f"{where}: pogo_accumulator_L must be a number (litres of gas per engine on the oxidizer "
                      "line) or {'ox': litres, 'fuel': litres}")


def default_levels(elements):
    """Give each payload element without a set acoustic level its predicted liftoff level plus the protoqualification
    margin, at least the baseline. elements: the whole stack, bottom first, after the fairing and aeroshell layout."""
    levels = liftoff_acoustics(elements)["levels"]
    for e in elements:
        if e.vibro_payload and e.id in levels:
            e.qual_acoustic_default = max(DEFAULT_QUAL_ACOUSTIC_DB, round(levels[e.id] + ACOUSTIC_PROTOQUAL_MARGIN_DB, 1))
            if not e.qual_acoustic_set:
                e.qual_acoustic_dB = e.qual_acoustic_default


def hardening_mass(e):
    """Mass to add (or save, below the default levels) for this element's qualification levels."""
    if e.kind == "fairing":
        return 0.0
    ra = 10 ** ((e.qual_acoustic_dB - getattr(e, "qual_acoustic_default", DEFAULT_QUAL_ACOUSTIC_DB)) / 20)
    rs = e.qual_shock_g / DEFAULT_QUAL_SHOCK_G
    base = sum(v for k, v in e.mass_breakdown.items()
               if not any(w in k for w in ("tank", "engine", "helium", "copv", "residual", "propellant", "accumulator",
                                           "tps", "ballast", "vibration")))
    return STRUCTURE_FRACTION * base * (max(ra, rs) - 1.0)


def accumulator_mass(e):
    """Gas vessel of each accumulator: a sphere at the pump inlet pressure, of the stage's material at its
    proof factor (the same rule as the tanks: m = 3/2 p V rho / (sy / proof))."""
    if not e.pogo_accumulator_L or not e.engines:
        return 0.0
    n_eng = sum(n for en, n in e.engines if en.cycle != "pressure_fed")
    mat = D.MATERIALS.get(e.material or "Al2219", D.MATERIALS["Al2219"])
    p = max(e.tank_pressure, 1e5) * 1.5
    vol = sum(e.pogo_accumulator_L.values()) / 1e3 * n_eng
    return 1.5 * p * vol * mat["rho"] / (mat["sy"] / D.PROOF_FACTOR_UNTESTED)


# ---------------------------------------------------------------------------- acoustic environment
def _heights(elements):
    """Height of each element's base above the bottom of the stack (the nozzle exit plane), and of the payload
    compartment's middle for the elements a fairing covers."""
    inside = set()
    for e in elements:
        inside.update(e.spec.get("_inside", []))
    z, base, mid = 0.0, {}, {}
    for e in elements:
        base[e.id] = z
        if e.kind == "fairing" or e.kind == "parachute" or e.id in inside:
            mid[e.id] = z
            continue
        mid[e.id] = z + e.length / 2
        z += e.length
    for e in elements:
        if e.kind == "fairing":
            for c in e.spec.get("_covers", []):
                mid[c] = base[e.id] + e.length / 2
    return mid


def liftoff_acoustics(elements, p_amb=101325.0, rho_c=EARTH_RHO_C):
    """The overall sound pressure level (dB) at each payload element (payload_flags) at liftoff, and the inputs.
    elements: the stack at liftoff, bottom first (Element objects). p_amb and rho_c: the air at the pad (sea
    level by default; a Mars site's for a Mars ascent)."""
    if not elements or not elements[0].engines:
        return {"levels": {}}
    first = elements[0]
    F = sum(en.thrust(1.0, p_amb) * n for en, n in first.engines)
    mdot = sum(en.mdot * n for en, n in first.engines)
    Ue = sum(en.thrust_vac * n for en, n in first.engines) / mdot if mdot else 0.0
    if F <= 0 or Ue <= 0:
        return {"levels": {}}
    Lw = 10 * math.log10(SP8072_POWER_FACTOR * F * Ue) + 120.0
    air_dB = 10 * math.log10(rho_c / EARTH_RHO_C) if rho_c != EARTH_RHO_C else 0.0
    mid = _heights(elements)
    levels = {}
    for e, pay in zip(elements, payload_flags([x.kind for x in elements])):
        if not pay:
            continue
        r = max(mid[e.id], 1.0)
        levels[e.id] = Lw - 20 * math.log10(r) - FAIRING_K_DB + air_dB
    return {"levels": levels, "Lw_dB": Lw, "thrust_N": F, "Ue_mps": Ue, "r_m": {k: mid[k] for k in levels},
            "air_dB": air_dB}


def aero_noise_dB(q, mach):
    """The noise inside the fairing (or at a capsule's wall) from the boundary layer outside, in dB: NASA-HDBK-7005
    eq. 4.14 less the fairing's noise reduction. q in Pa. Returns (interior level, exterior level, Cq)."""
    if q <= 0:
        return -math.inf, -math.inf, 0.0
    cq = TBL_CQ_SEPARATED if TRANSONIC_MACH[0] <= mach <= TRANSONIC_MACH[1] else TBL_CQ_ATTACHED
    ext = 20 * math.log10(cq * q / math.sqrt(1 + 0.14 * mach * mach) / 2e-5)
    return ext - FAIRING_NR_DB, ext, cq


def octave_spectrum(oaspl):
    """Full-octave levels with the shape of the Falcon 9 spectrum, scaled to an overall level."""
    return {f: v + oaspl - FALCON9_OASPL_DB for f, v in FALCON9_OCTAVE_DB.items()}


def separation_shock(order, eid, joints=None):
    """{element id: SRS peak g} for the elements on both sides of the plane where eid leaves the stack, and with
    the joint attenuation (VIBRO_SHOCK_JOINTS) for the elements beyond them: 40% less per joint in between,
    for up to three joints. order: element objects present, bottom first. A fairing's plane is at its base, beside
    the element below it and the first element it covers. joints: None reads the switch."""
    ids = [e.id for e in order]
    if eid not in ids:
        return {}
    i = ids.index(eid)
    out = {eid: SEPARATION_SHOCK_G}
    if i > 0:
        out[ids[i - 1]] = SEPARATION_SHOCK_G
    if i + 1 < len(ids):
        out[ids[i + 1]] = SEPARATION_SHOCK_G
    if switch("VIBRO_SHOCK_JOINTS") if joints is None else joints:
        for k, other in enumerate(ids):
            if other in out:
                continue
            n = (k - (i + 1)) if k > i else ((i - 1) - k)
            out[other] = SEPARATION_SHOCK_G * (1 - JOINT_ATTENUATION) ** min(n, MAX_JOINTS)
    return out


# ---------------------------------------------------------------------------- pogo
def _chain(stack):
    """Lumped masses and springs of the stack, bottom first: [(mass, k to the next node)], and the node of each
    stage's engines. stack: [(Element, fuel kg, ox kg, total mass kg)], bottom first.

    A stage is three nodes: its base (engines, thrust structure and the lower tank's liquid, which rests on that
    tank's lower dome), the base of the upper tank (that tank's liquid) and its top. The tank walls between
    them are springs E A / L, with A the wall (and smeared stiffener) area. Each node carries a third of the
    stage's dry mass. Other elements ride on the stage below as rigid masses: a fairing, a capsule or an
    aeroshell is much stiffer along the axis than a long tank."""
    masses, springs, eng = [], [], {}
    k_rigid = None
    for e, fuel, ox, m_tot in stack:
        if e.is_stage and e.tanks and e.material in D.MATERIALS:
            E = D.MATERIALS[e.material]["E"]
            smear = e.stiffeners.get("smear", 0.0) if e.stiffeners else 0.0
            lower, upper = e.tanks["fuel"], e.tanks["ox"]
            liq_lo, liq_up = fuel, ox
            dry = max(m_tot - fuel - ox, 0.0)
            k1 = E * 2 * math.pi * lower.radius * (lower.wall_t + smear) / max(lower.length, 0.1)
            k2 = E * 2 * math.pi * upper.radius * (upper.wall_t + smear) / max(upper.length, 0.1)
            if masses:
                springs.append(k1 * 4.0)           # the interstage: short, stiff
            eng[e.id] = len(masses)
            masses += [dry / 3 + liq_lo, dry / 3 + liq_up, dry / 3]
            springs += [k1, k2]
            k_rigid = max(k_rigid or 0.0, 10 * max(k1, k2))
        elif not masses:
            masses.append(m_tot)
        else:
            masses[-1] += m_tot
    return masses, springs, eng


def first_mode(stack):
    """First longitudinal mode of the free-free chain: (frequency Hz, mode shape, node of each stage's engines)."""
    m, k, eng = _chain(stack)
    n = len(m)
    if n < 2 or len(k) != n - 1:
        return None, None, eng
    K = np.zeros((n, n))
    for i, ki in enumerate(k):
        K[i, i] += ki
        K[i + 1, i + 1] += ki
        K[i, i + 1] -= ki
        K[i + 1, i] -= ki
    Mi = 1.0 / np.sqrt(np.array(m))
    A = K * Mi[:, None] * Mi[None, :]
    w2, v = np.linalg.eigh(A)
    j = 1 if n > 1 else 0                     # skip the rigid-body mode
    phi = v[:, j] * Mi
    return math.sqrt(max(w2[j], 0.0)) / (2 * math.pi), (phi, np.array(m)), eng


def feed_frequency(e, role, en, n, accel, l=None):
    """Resonance of one propellant's suction line (Hz) and its inertance (kg/m^4) and compliance (m^3/Pa) per
    engine. The lower tank's line runs through the engine section, the upper tank's also along the lower tank.
    l: a line length to use instead (m), for the local pogo check's short duct."""
    prop = e.fuel if role == "fuel" else e.ox
    rho = _propellant_rho(prop)
    of = en.of
    mdot_role = en.mdot * (of / (1 + of) if role == "ox" else 1 / (1 + of))
    Q = mdot_role / rho
    S = Q / LINE_SPEED
    if l is None:
        tank_len = sum(t.length for t in e.tanks.values())
        l = max(e.length - tank_len, 0.5) + (e.tanks["fuel"].length if role == "ox" else 0.0)
    L = rho * l / S
    C = CAVITATION_COMPLIANCE_PER_FLOW * Q
    acc_L = e.pogo_accumulator_L.get(role, 0.0) if getattr(e, "pogo_accumulator_L", None) else 0.0
    if acc_L > 0:
        p_in = e.tank_pressure + rho * max(accel, 0.0) * l
        C += acc_L / 1e3 / (GAS_GAMMA * p_in)
    return 1 / (2 * math.pi * math.sqrt(L * C)), L, C, S, rho


def lewis_n():
    """Lewis's force-feedback gain at resonance: his worked example's, or the TN D-5714 refit."""
    return LEWIS_N_TN5714 if switch("VIBRO_POGO_TN5714") else LEWIS_N


def _lewis_zeta(K, w, fp):
    """Damping needed for neutral stability from one line (Lewis eq. 35, simplified): K n cos(psi) cos(theta + psi)."""
    psi = math.atan(FEED_Q * (1 - (w / (2 * math.pi * fp)) ** 2))
    return K * lewis_n() * math.cos(psi) * math.cos(LEWIS_THETA + psi)


def aft_role(e):
    """The propellant of the aft tank, whose dome the crossbeam carries (LOX_AFT_FUELS)."""
    return "ox" if e.fuel in LOX_AFT_FUELS else "fuel"


def local_pogo(e, en, n, thr, aft_left, accel):
    """The local pogo mode of a center engine on a crossbeam, or None when the stage has no center engine.
    e: the stage; en, n, thr: its pump-fed engine, count and throttle; aft_left: kg left in the aft tank.
    Returns {"f_local", "f_line", "zeta_needed", "margin_dB", "unstable", "lox_aft"}."""
    if n < LOCAL_POGO_MIN_ENGINES or n % 2 == 0 or en.cycle == "pressure_fed" or not e.diameter:
        return None
    if aft_left <= 0:
        return None
    lox_aft = aft_role(e) == "ox"
    k = CROSSBEAM_STIFFNESS * en.thrust_vac / e.diameter
    m = en.mass + DOME_LIQUID_SHARE * aft_left
    w = math.sqrt(k / m)
    fp, L, C, S, rho = feed_frequency(e, "ox", en, 1, accel, l=LOCAL_DUCT_M if lox_aft else None)
    Ue = en.thrust_vac / en.mdot
    # Lewis eq. 4 for one engine on its own mode: the modal mass is the moving mass itself.
    zeta = _lewis_zeta(rho * Ue * S * thr / (2 * w * m), w, fp)
    margin = 20 * math.log10(STRUCTURAL_DAMPING / zeta) if zeta > 0 else float("inf")
    return {"f_local": w / (2 * math.pi), "f_line": fp, "zeta_needed": zeta, "margin_dB": margin,
            "unstable": zeta > STRUCTURAL_DAMPING, "lox_aft": lox_aft}


def pogo(stack, burning, accel, local=None):
    """Structural damping needed for neutral stability (Lewis's zeta_c) of each burning pump-fed stage.
    stack: [(Element, fuel, ox, mass)] bottom first. burning: {stage id: (engine, count, throttle)}.
    local: also check the local mode of a center engine (local_pogo); None reads the switch VIBRO_LOCAL_POGO.
    Returns {stage id: {"f_struct", "f_feed": {role: Hz}, "zeta_needed", "margin_dB", "unstable", "local"}}:
    "unstable" is the stack mode's; "local" holds the local mode's result (or None)."""
    f_s, mode, eng = first_mode(stack)
    out = {}
    if not f_s or mode is None:
        return out
    if local is None:
        local = switch("VIBRO_LOCAL_POGO")
    phi, m = mode
    w = 2 * math.pi * f_s
    els = {e.id: (e, fuel, ox) for e, fuel, ox, _ in stack}
    for sid, (en, n, thr) in burning.items():
        if sid not in eng or sid not in els or en.cycle == "pressure_fed":
            continue
        e, fuel, ox = els[sid]
        g = phi[eng[sid]]
        if abs(g) < 1e-12:
            continue
        Mn = float(np.sum(m * (phi / g) ** 2))   # modal mass at the gimbal point
        Ue = en.thrust_vac / en.mdot
        zeta, ff = 0.0, {}
        for role, left in (("fuel", fuel), ("ox", ox)):
            if left <= 0:
                continue
            fp, L, C, S, rho = feed_frequency(e, role, en, n, accel)
            ff[role] = fp
            # Lewis eq. 4 and 36: K = S_E H A / (2 w M); S_E H = dF/dQ = rho Ue for one propellant, A = the line area.
            K = rho * Ue * S * n * thr / (2 * w * Mn)
            zeta += _lewis_zeta(K, w, fp)
        margin = 20 * math.log10(STRUCTURAL_DAMPING / zeta) if zeta > 0 else float("inf")
        loc = local_pogo(e, en, n, thr, ox if aft_role(e) == "ox" else fuel, accel) if local else None
        out[sid] = {"f_struct": f_s, "f_feed": ff, "zeta_needed": zeta, "margin_dB": margin,
                    "unstable": zeta > STRUCTURAL_DAMPING, "local": loc}
    return out


def pogo_sweep(vehicle, samples=21, local=None):
    """Pogo of each pump-fed stage over its burn, firing bottom-up with everything above attached (the
    fairing stays on): [(stage id, fraction burned, pogo result)]. local: as in pogo()."""
    els = vehicle.elements
    out = []
    for i, e in enumerate(els):
        if not (e.is_stage and e.engines and e.tanks and sum(e.loaded.values()) > 0):
            continue
        pumped = [(en, n) for en, n in e.engines if en.cycle != "pressure_fed"]
        if not pumped:
            continue
        en, n = pumped[0]
        above = [(x, x.loaded.get("fuel", 0.0), x.loaded.get("ox", 0.0),
                  x.dry_mass + sum(x.loaded.values()) + x.rcs_prop) for x in els[i + 1:]]
        F = sum(x.thrust_vac * c for x, c in e.engines)
        for k in range(samples):
            fr = k / (samples - 1) * 0.999
            fuel, ox = e.loaded["fuel"] * (1 - fr), e.loaded["ox"] * (1 - fr)
            stack = [(e, fuel, ox, e.dry_mass + fuel + ox + e.rcs_prop)] + above
            a = F / sum(s[3] for s in stack)
            r = pogo(stack, {e.id: (en, n, 1.0)}, a, local=local).get(e.id)
            if r:
                out.append((e.id, fr, r))
    return out
