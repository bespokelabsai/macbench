BUNDLE = "{bundle}"


def unpack(root="/"):
    with tarfile.open(fileobj=io.BytesIO(base64.b64decode(BUNDLE)), mode="r:gz") as tf:
        try:
            tf.extractall(root, filter="data")
        except TypeError:   # Python before 3.11.4 has no extraction filters
            tf.extractall(root)


try:
    unpack()
    os.environ["MARSFLIGHT_ROLES_PY"] = "/opt/marsflight-task/roles.py"
except PermissionError:   # the board does not run as root: unpack under its home, and point the program office there
    home = os.path.join(os.path.expanduser("~"), "marsflight-hub")
    unpack(home)
    os.environ["MARSFLIGHT_PROGRAM_PYTHONPATH"] = f"{home}/opt/marsflight:{home}/opt/designlang"
